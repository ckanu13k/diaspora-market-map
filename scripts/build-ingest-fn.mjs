// Generates supabase/functions/ingest-osm/index.ts as ONE self-contained file
// (shared taxonomy + OSM mapping + handler), so it can be deployed from the Supabase dashboard editor.
import { readFileSync, writeFileSync } from 'node:fs';
const core = readFileSync('scripts/osm-core.mjs', 'utf8').replace('export function createOsm', 'function createOsm');
const taxonomy = readFileSync('shared/taxonomy.json', 'utf8');
const handler = readFileSync('supabase/functions/ingest-osm/handler.ts', 'utf8').replace(/declare const createOsm[\s\S]*?declare const TAXONOMY: unknown;\n/, '');
const [imports, ...rest] = handler.split(/\n(?=const osm)/);
writeFileSync('supabase/functions/ingest-osm/index.ts',
  `// @ts-nocheck — GENERATED by scripts/build-ingest-fn.mjs; edit handler.ts / osm-core.mjs / taxonomy.json instead.\n${imports}\n\n${core}\nconst TAXONOMY = ${taxonomy.trim()};\n\n${rest.join('\n')}`);
console.log('wrote supabase/functions/ingest-osm/index.ts');
